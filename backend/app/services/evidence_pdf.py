"""One-page evidence summary PDF (fpdf2, core fonts). Facts only, from the database."""
from __future__ import annotations

import unicodedata
from typing import Any

from fpdf import FPDF

_REPL = {"‘": "'", "’": "'", "“": '"', "”": '"', "–": "-", "—": "-", "…": "...", "→": "->", "·": "-"}


def _latin(s: Any) -> str:
    text = "".join(_REPL.get(ch, ch) for ch in str(s if s is not None else "-"))
    return unicodedata.normalize("NFKD", text).encode("latin-1", "ignore").decode("latin-1")


def build_summary_pdf(facts: dict[str, Any]) -> bytes:
    pdf = FPDF(format="Letter")
    pdf.set_auto_page_break(True, margin=15)
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 15)
    pdf.cell(0, 9, _latin("Shipment evidence summary"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(90, 90, 90)
    pdf.cell(0, 5, _latin(f"PayPal dispute {facts.get('dispute_id')} - generated by StayCovered from stored records"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)
    pdf.ln(3)

    def section(title: str, rows: list[tuple[str, Any]]) -> None:
        pdf.set_font("Helvetica", "B", 11)
        pdf.set_fill_color(240, 243, 247)
        pdf.cell(0, 7, _latin(title), new_x="LMARGIN", new_y="NEXT", fill=True)
        pdf.set_font("Helvetica", "", 10)
        for k, v in rows:
            pdf.set_font("Helvetica", "B", 10)
            pdf.cell(55, 6, _latin(k))
            pdf.set_font("Helvetica", "", 10)
            pdf.multi_cell(0, 6, _latin(v), new_x="LMARGIN", new_y="NEXT")
        pdf.ln(2)

    section("PayPal payment", [
        ("PayPal order ID", facts.get("paypal_order_id")),
        ("Capture ID", facts.get("capture_id")),
        ("Amount", f"{facts.get('amount')} {facts.get('currency')}"),
        ("Payment date", facts.get("payment_date")),
        ("Item", facts.get("item")),
    ])
    a = facts.get("protected_address") or {}
    section("Protected shipping address (from the PayPal transaction)", [
        ("Recipient", a.get("name")),
        ("Address", ", ".join(x for x in [a.get("line1"), a.get("line2")] if x)),
        ("City / State / ZIP", f"{a.get('city')}, {a.get('state')} {a.get('postal_code')}"),
        ("Country", a.get("country")),
    ])
    lab = facts.get("label") or {}
    section("Shipping label check (before dispatch)", [
        ("Label address read", lab.get("address_text")),
        ("Comparison with PayPal address", lab.get("comparison")),
        ("Pre-shipment verdict", facts.get("verdict")),
    ])
    ships = facts.get("shipments") or []
    section("Shipment and tracking (registered with PayPal)", [
        (f"Parcel {i + 1}", f"{s['carrier']} {s['tracking_number']} - shipped {s['ship_date']} - tracker registered {s['registered_at']} - status {s['status']}")
        for i, s in enumerate(ships)
    ] or [("Tracking", "none registered")])
    events = facts.get("timeline") or []
    section("Timeline", [(e["when"], e["what"]) for e in events[:14]] or [("-", "no events")])
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(110, 110, 110)
    pdf.multi_cell(0, 4, _latin("All facts above come from PayPal API responses and StayCovered's audit log for this order. "
                                "PayPal makes the final decision on this dispute."))
    return bytes(pdf.output())
